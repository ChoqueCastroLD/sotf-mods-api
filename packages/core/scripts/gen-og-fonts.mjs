/**
 * Embeds the Onest WOFF files of `src/og/fonts/` into `src/og/fonts/onest.gen.ts` as base64, so the
 * worker bundle (tsdown) carries them and needs no font files at runtime.
 *
 *   node packages/core/scripts/gen-og-fonts.mjs
 *
 * The WOFF files are static instances (wght 400 and 700) of the Onest variable font (SIL OFL 1.1),
 * cut with fontTools from `@fontsource-variable/onest` (the latin, latin-ext, vietnamese, cyrillic
 * and cyrillic-ext woff2 files):
 *
 *   from fontTools.ttLib import TTFont
 *   from fontTools.varLib import instancer
 *   font = instancer.instantiateVariableFont(TTFont('onest-latin-wght-normal.woff2'), {'wght': 700})
 *   font.flavor = 'woff'; font.save('onest-latin-700.woff')
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '../src/og/fonts');
const subsets = ['latin', 'latin-ext', 'vietnamese', 'cyrillic', 'cyrillic-ext'];
const entries = subsets.flatMap((subset) =>
  [400, 700].map((weight) => {
    const base64 = readFileSync(join(dir, `onest-${subset}-${weight}.woff`)).toString('base64');
    return `  { subset: '${subset}', weight: ${weight}, base64: '${base64}' },`;
  }),
);
writeFileSync(
  join(dir, 'onest.gen.ts'),
  `// Generated by scripts/gen-og-fonts.mjs. Do not edit by hand.\n// Onest static instances (SIL OFL 1.1), WOFF, base64.\n\nexport const ONEST_WOFF: ReadonlyArray<{ readonly subset: string; readonly weight: 400 | 700; readonly base64: string }> = [\n${entries.join('\n')}\n];\n`,
);
