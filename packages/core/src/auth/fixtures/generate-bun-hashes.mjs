// Generates bun-hashes.json with the password hashing of the legacy API (Bun's `Bun.password`),
// so the v2 verifier is tested against hashes produced by the real legacy runtime (PLAN §6.10).
//
//   npx bun@1.4 run packages/core/src/auth/fixtures/generate-bun-hashes.mjs
//
// The passwords are throwaway test values. Re-running produces different salts (same semantics).
/* global Bun */
import { writeFileSync } from 'node:fs';

const ascii = 'kelvin-carries-logs-2026';
const unicode = 'Pässwörd#1ñ€漢'.normalize('NFC');
// > 72 UTF-8 bytes: Bun's bcrypt pre-hashes it with SHA-512 (non-standard behaviour).
const long = `${'virginia-'.repeat(9)}ümlaut-ñ`;

const cases = [
  { name: 'argon2id-ascii', algorithm: 'argon2id', password: ascii, hash: await Bun.password.hash(ascii) },
  { name: 'argon2id-unicode-nfc', algorithm: 'argon2id', password: unicode, hash: await Bun.password.hash(unicode) },
  {
    name: 'bcrypt-ascii',
    algorithm: 'bcrypt',
    password: ascii,
    hash: await Bun.password.hash(ascii, { algorithm: 'bcrypt', cost: 10 }),
  },
  {
    name: 'bcrypt-long',
    algorithm: 'bcrypt',
    password: long,
    hash: await Bun.password.hash(long, { algorithm: 'bcrypt', cost: 10 }),
  },
];
for (const c of cases) {
  if (!(await Bun.password.verify(c.password, c.hash))) throw new Error(`self-check failed for ${c.name}`);
}

const out = {
  $comment: 'Generated by generate-bun-hashes.mjs with Bun.password (the legacy API runtime). Test data only.',
  generator: `bun ${Bun.version}`,
  longPasswordBytes: new TextEncoder().encode(long).length,
  cases,
};
writeFileSync(new URL('./bun-hashes.json', import.meta.url), `${JSON.stringify(out, null, 2)}\n`);
process.stdout.write(`wrote ${cases.length} hashes with bun ${Bun.version}\n`);
